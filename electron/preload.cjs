const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('ace', {
  isElectron: true,
  fetchData: (url, opts) => ipcRenderer.invoke('data:fetch', url, opts),
  clearCache: () => ipcRenderer.invoke('data:clearCache'),
  listChars: () => ipcRenderer.invoke('chars:list'),
  loadChar: (id) => ipcRenderer.invoke('chars:load', id),
  saveChar: (c) => ipcRenderer.invoke('chars:save', c),
  deleteChar: (id) => ipcRenderer.invoke('chars:delete', id),
  saveImage: (charId, dataUrl) => ipcRenderer.invoke('img:save', charId, dataUrl),
  loadImage: (charId, name) => ipcRenderer.invoke('img:load', charId, name),
  deleteImage: (charId, name) => ipcRenderer.invoke('img:delete', charId, name),
  getSettings: () => ipcRenderer.invoke('settings:get'),
  setSettings: (s) => ipcRenderer.invoke('settings:set', s),
  saveFile: (o) => ipcRenderer.invoke('file:save', o),
  openFile: (o) => ipcRenderer.invoke('file:open', o),
  saveFilesToDir: (o) => ipcRenderer.invoke('file:saveDir', o),
  openExternal: (u) => ipcRenderer.invoke('sys:openExternal', u),
  hardware: () => ipcRenderer.invoke('sys:hardware'),
  version: () => ipcRenderer.invoke('app:version'),
  checkUpdate: () => ipcRenderer.invoke('update:check'),
  ai: {
    status: () => ipcRenderer.invoke('ai:status'),
    updates: () => ipcRenderer.invoke('ai:updates'),
    install: (o) => ipcRenderer.invoke('ai:install', o),
    cancel: () => ipcRenderer.invoke('ai:cancel'),
    start: () => ipcRenderer.invoke('ai:start'),
    stop: () => ipcRenderer.invoke('ai:stop'),
    generate: (p) => ipcRenderer.invoke('ai:generate', p),
    log: () => ipcRenderer.invoke('ai:log'),
    skip: () => ipcRenderer.invoke('ai:skip'),
    setIdle: (m) => ipcRenderer.invoke('ai:setIdle', m),
    chooseDir: () => ipcRenderer.invoke('ai:chooseDir'),
    openDir: () => ipcRenderer.invoke('ai:openDir'),
    on: (ch, cb) => { const h = (_e, d) => cb(d); ipcRenderer.on(ch, h); return () => ipcRenderer.removeListener(ch, h); },
  },
  trellis: {
    status: () => ipcRenderer.invoke('trellis:status'),
    start: () => ipcRenderer.invoke('trellis:start'),
    stop: () => ipcRenderer.invoke('trellis:stop'),
    log: () => ipcRenderer.invoke('trellis:log'),
    generate: (p) => ipcRenderer.invoke('trellis:generate', p),
    load: (o) => ipcRenderer.invoke('trellis:load', o),
    remove: (o) => ipcRenderer.invoke('trellis:delete', o),
    exportGlb: (o) => ipcRenderer.invoke('trellis:export', o),
    install: () => ipcRenderer.invoke('trellis:install'),
    openDir: (id) => ipcRenderer.invoke('trellis:openDir', id),
    on: (ch, cb) => { const h = (_e, d) => cb(d); ipcRenderer.on(ch, h); return () => ipcRenderer.removeListener(ch, h); },
  },
  installUpdate: (info) => ipcRenderer.invoke('update:install', info),
  onUpdateProgress: (cb) => { const h = (_e, p) => cb(p); ipcRenderer.on('update:progress', h); return () => ipcRenderer.removeListener('update:progress', h); },
});
